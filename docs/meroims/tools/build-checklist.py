#!/usr/bin/env python3
"""Rebuild docs/feature-checklist.md from evidence (driver runs + REA shape files).
Status is derived only from what was actually captured; nothing is marked inspected by hand."""
import glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHELL = re.compile(r'^GET /api/(account-config|core/billing/status|core/branches/mine|core/me|core/notifications|events/stream|overview)$')

shape_eps = set()
for f in glob.glob(f'{ROOT}/evidence/captures/shapes-*.txt'):
    for line in open(f):
        if line.startswith('## '):
            shape_eps.add(re.sub(r' \?\{.*', '', line[3:].strip()))

rows, all_api, blocked_total, nav_soft = [], set(), 0, 0
for f in sorted(glob.glob(f'{ROOT}/evidence/routes/b*.json')):
    d = json.load(open(f)); batch = os.path.basename(f)[:-5]
    blocked_total += len(d.get('blocked', []))
    for s in d['steps']:
        ui = s.get('ui') or {}
        calls = sorted({f"{a['method']} {a['path']}" for a in d['api'] if a['step'] == s['id'] or a['step'].startswith(s['id'] + '#')})
        calls = [c for c in calls if not SHELL.match(c)]
        all_api.update(calls)
        heads = ' '.join(ui.get('headings', []))
        empty = ui.get('emptyStates', [])
        opened = s.get('opened') or {}
        if s.get('error'):
            status, note = '⛔ Blocked', s['error'][:80]
        elif 'Coming soon' in heads:
            status, note = '⛔ Not implemented', 'page shows "Coming soon"; no API calls'
        else:
            status = '✅ Inspected'
            notes = []
            if opened.get('result') == 'no-rows' or empty: notes.append('no records to open (empty in tenant)' if opened.get('result') == 'no-rows' else 'empty state shown')
            if opened.get('result') == 'clicked' and opened.get('to') != opened.get('from'): notes.append(f"detail page {opened['to']}")
            elif opened.get('result') == 'clicked': notes.append('row opened in-page')
            if s.get('tabViews'): notes.append(f"{len([t for t in s['tabViews'] if t.get('ui')])} tabs walked")
            if s.get('skippedTabs'): notes.append('tabs skipped: ' + ', '.join(s['skippedTabs']))
            note = '; '.join(notes)
        shaped = sum(1 for c in calls if c in shape_eps)
        rows.append((ui.get('path', '?'), (ui.get('headings') or [s['id']])[0], status, len(ui.get('fields', [])), len(calls), shaped, note, batch))

out = [
    '# MeroIMS Feature / Route Checklist (Admin scope) — evidence-generated',
    '',
    'Generated by `tools/build-checklist.py` from `evidence/routes/b*.json` (CDP driver) and `evidence/captures/shapes-*.txt` (REA value-free shapes).',
    '**✅ Inspected** means the route was visited, its UI was inventoried (headings, actions, tabs, fields, columns), and the API calls it triggered were recorded.',
    'It does **not** mean write flows were exercised: no form was saved and no record was created, posted or deleted.',
    '',
    f'- Routes visited: **{len(rows)}** · write attempts blocked by the network guard: **{blocked_total}**',
    f'- Distinct non-shell API operations seen on routes: **{len(all_api)}** · endpoints with value-free shapes (all rounds): **{len(shape_eps)}**',
    '',
    '| Route | Page | Status | Fields | API ops | w/ shapes | Notes | Dossier |',
    '|---|---|---|---|---|---|---|---|',
]
for r in rows:
    out.append(f'| `{r[0]}` | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} | [{r[7]}](routes/{r[7]}.md) |')
out += ['', '_Workflow-level status and open gaps: see the "Workflow coverage" section of `00-master-index.md`._', '']
open(f'{ROOT}/docs/feature-checklist.md', 'w').write('\n'.join(out))
print(f'routes={len(rows)} blocked={blocked_total} api_ops={len(all_api)} shaped_endpoints={len(shape_eps)}')
print('status counts:', {s: sum(1 for r in rows if r[2] == s) for s in sorted({r[2] for r in rows})})
