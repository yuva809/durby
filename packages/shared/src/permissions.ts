/** Replaces each legacy key by the keys it stands for; other keys stay as they are, in order, without repeats. */
export function expandLegacyKeys(keys: Iterable<string>): string[] {
  const out = new Set<string>();
  for (const key of keys) {
    const replacements = LEGACY_PERMISSION_ALIASES[key];
    if (replacements) for (const r of replacements) out.add(r);
    else out.add(key);
  }
  return [...out];
}
