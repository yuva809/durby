#!/usr/bin/env bash
# Adds a second Durby stack (e.g. the dev environment) to a host that already runs one (ADR 0034). The existing
# stack (EDGE_DIR, default /opt/durby) keeps its Caddy, which also serves the new stack's domains. Run once, as root:
#
#   STACK=dev DEPLOY_BRANCH=development DOMAIN=dev.durby.tech DEMO_DOMAIN=partner-dev.durby.tech \
#     bash /opt/durby/bin/add-stack.sh
#
# Then, as deploy: cd /opt/durby-$STACK && bin/release.sh   (docs/ops/deploy.md → Environments and branches)
# Safe to re-run: an existing .env, Caddy site or backup timer is left unchanged.
set -euo pipefail

STACK="${STACK:-}"
EDGE_DIR="${EDGE_DIR:-/opt/durby}"
ROOT="${ROOT:-}" # tests only: prefix for every path written
SYSTEMCTL="${SYSTEMCTL:-systemctl}"

log() { printf '\n==> %s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

[[ "$STACK" =~ ^[a-z][a-z0-9]{0,15}$ ]] || die "set STACK to a short lowercase name, e.g. dev"
[[ "$STACK" != prod ]] || die "prod is the edge stack's own alias"
[[ -n "${DEPLOY_BRANCH:-}" ]] || die "set DEPLOY_BRANCH (e.g. development)"
[[ -n "${DOMAIN:-}" && -n "${DEMO_DOMAIN:-}" ]] || die "set DOMAIN and DEMO_DOMAIN (DNS A records to this host)"
[[ -z "$ROOT" && $EUID -ne 0 ]] && die "run as root"
DIR="$ROOT${STACK_DIR:-/opt/durby-$STACK}"
EDGE="$ROOT$EDGE_DIR"
[[ -f "$EDGE/.env" && -d "$EDGE/bin" ]] || die "no stack in $EDGE (EDGE_DIR)"
own() { [[ -n "$ROOT" ]] || chown "$@"; }
edge_value() { sed -n "s/^$1=//p" "$EDGE/.env" | tail -n 1 | tr -d "'\""; }

log "Directory $DIR"
install -d -m 750 "$DIR" "$DIR/state" "$DIR/bin"
install -d -m 700 "$DIR/backups"
cp -p "$EDGE"/bin/* "$DIR/bin/"
own -R deploy:deploy "$DIR"

if [[ ! -f "$DIR/.env" ]]; then
  log "Generating $DIR/.env"
  secret() { openssl rand -hex 32; }
  (
    umask 077
    cat >"$DIR/.env" <<EOF
# Generated by add-stack.sh on $(date -u +%F): stack "$STACK" next to $EDGE_DIR (ADR 0034). Never commit.
COMPOSE_PROJECT_NAME=durby-$STACK
DEPLOY_BRANCH=$DEPLOY_BRANCH
# Served by the Caddy of $EDGE_DIR (caddy/extra/$STACK.caddy), through the shared network.
EDGE=false
SHARED_ALIAS=$STACK
MAILPIT_UI_PORT=${MAILPIT_UI_PORT:-8026}
# Local images only, so this stack's image cleanup never touches the other stack's releases.
IMAGE_PREFIX=local/durby-$STACK

POSTGRES_SUPERUSER_PASSWORD=$(secret)
DURBY_MIGRATOR_PASSWORD=$(secret)
DURBY_APP_PASSWORD=$(secret)
REDIS_PASSWORD=$(secret)
JWT_ACCESS_SECRET=$(secret)

STAGING_DOMAIN=$DOMAIN
STAGING_DEMO_DOMAIN=$DEMO_DOMAIN
ACME_EMAIL=$(edge_value ACME_EMAIL)
MAIL_FROM=Durby ${STACK^} <no-reply@$DOMAIN>

LOG_LEVEL=info
# A smaller Postgres than the edge stack's, to share the host's memory.
POSTGRES_MEMORY=512m
POSTGRES_SHARED_BUFFERS=128MB
POSTGRES_CACHE_SIZE=256MB

BACKUP_RCLONE_REMOTE=storagebox:durby-$DEPLOY_BRANCH
BACKUP_AGE_RECIPIENT=$(edge_value BACKUP_AGE_RECIPIENT)
BACKUP_HEARTBEAT_URL=
EOF
  )
  [[ -n "$(edge_value DEPLOY_REPO)" ]] && echo "DEPLOY_REPO=$(edge_value DEPLOY_REPO)" >>"$DIR/.env"
  own deploy:deploy "$DIR/.env"
  chmod 600 "$DIR/.env"
else
  log "$DIR/.env exists; left unchanged"
fi

site="$EDGE/caddy/extra/$STACK.caddy"
if [[ ! -f "$site" ]]; then
  log "Caddy site $site"
  install -d -m 755 "$EDGE/caddy/extra"
  cat >"$site" <<EOF
# Stack "$STACK" ($DIR), written by add-stack.sh (ADR 0034). Not in the repo; deploys leave it alone.
$DOMAIN, $DEMO_DOMAIN {
	import durby $STACK-api:4000 $STACK-web:3000
}
EOF
  own -R deploy:deploy "$EDGE/caddy/extra"
else
  log "$site exists; left unchanged"
fi

log "Nightly backup timer for $STACK (03:30 UTC)"
units="$ROOT/etc/systemd/system"
install -d "$units"
cat >"$units/durby-backup-$STACK.service" <<EOF
[Unit]
Description=Durby $STACK Postgres backup
After=docker.service
Requires=docker.service
ConditionPathExists=${DIR#"$ROOT"}/bin/backup.sh

[Service]
Type=oneshot
User=deploy
Group=deploy
ExecStart=${DIR#"$ROOT"}/bin/backup.sh
EOF
cat >"$units/durby-backup-$STACK.timer" <<EOF
[Unit]
Description=Nightly Durby $STACK Postgres backup

[Timer]
OnCalendar=*-*-* 03:30:00 UTC
RandomizedDelaySec=10m
Persistent=true

[Install]
WantedBy=timers.target
EOF
if [[ -z "$ROOT" ]]; then
  "$SYSTEMCTL" daemon-reload
  "$SYSTEMCTL" enable --now "durby-backup-$STACK.timer"
fi

cat <<EOF

Done. Next:
  1. DNS: A records for $DOMAIN and $DEMO_DOMAIN to this host.
  2. As deploy:  cd ${DIR#"$ROOT"} && bin/release.sh
  3. As deploy:  cd $EDGE_DIR && bin/dc exec caddy caddy reload --config /etc/caddy/Caddyfile
     (the edge stack's compose and Caddyfile must already be the ADR 0034 version: bin/release.sh there first)
  Mail UI: ssh -L ${MAILPIT_UI_PORT:-8026}:127.0.0.1:${MAILPIT_UI_PORT:-8026} <you>@<host>
EOF
